"""Build the Windows installer: a self-contained Python, the app, the built interface, and an
Inno Setup wrapper. Models and the llama.cpp runtime are not in it; `app.download` fetches them
on first run.

    python installer/build.py           stage and compile, into dist/
    python installer/build.py --lock    re-resolve installer/requirements.txt, with hashes

Needs Inno Setup 6 (`ISCC.exe`, found on PATH, in its default locations, or via --iscc) and the
interface built (`npm --prefix ui run build`).
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
import urllib.request
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
HERE = REPO / "installer"
CACHE = REPO / "build" / "installer-cache"
STAGE = REPO / "build" / "installer" / "Mockingbird"
DIST = REPO / "dist"
REQUIREMENTS = HERE / "requirements.txt"

PYTHON = "3.12.10"
PYTHON_URL = "https://www.python.org/ftp/python/%s/python-%s-embed-amd64.zip" % (PYTHON, PYTHON)
# Pinned on first download, 07/11/2026, after python.exe and python312.dll inside verified as
# Authenticode-signed by the Python Software Foundation.
PYTHON_SHA256 = "4acbed6dd1c744b0376e3b1cf57ce906f9dc9e95e68824584c8099a63025a3c3"
# The whole closure, pinned to the versions the test suite runs against; --lock adds hashes.
TOP = ["fastapi==0.141.1", "uvicorn==0.52.4", "websockets==17.1", "numpy==2.5.2",
       "sherpa-onnx==1.13.6", "sherpa-onnx-core==1.13.6", "pip==26.2.1",
       "starlette==1.6.0", "pydantic==2.13.5", "pydantic-core==2.46.5", "anyio==4.14.2",
       "click==8.5.0", "colorama==0.4.6", "h11==0.16.0", "idna==3.19",
       "annotated-doc==0.0.5", "annotated-types==0.8.0", "typing-extensions==4.16.0",
       "typing-inspection==0.4.4"]

SHIP = ["app", "api", "config", "ui/build", "LICENSE", "LICENSES", "THIRD_PARTY_NOTICES.md",
        "README.md"]
ISCC_GUESSES = [Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Inno Setup 6" / "ISCC.exe",
                Path(r"C:\Program Files (x86)\Inno Setup 6\ISCC.exe"),
                Path(r"C:\Program Files\Inno Setup 6\ISCC.exe")]


def version() -> str:
    return tomllib.loads((REPO / "pyproject.toml").read_text(encoding="utf-8"))["project"]["version"]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while block := f.read(1 << 20):
            h.update(block)
    return h.hexdigest()


def pip(*args: str) -> None:
    subprocess.run([sys.executable, "-m", "pip", "--disable-pip-version-check", *args],
                   check=True)


def lock() -> None:
    """Resolve TOP for CPython 3.12 on win_amd64, binary wheels only, and record every file's
    hash, so the build installs exactly these bytes or nothing."""
    with tempfile.TemporaryDirectory() as tmp:
        pip("download", "--only-binary", ":all:", "--platform", "win_amd64",
            "--python-version", "3.12", "--implementation", "cp", "-d", tmp, *TOP)
        lines = []
        for whl in sorted(Path(tmp).glob("*.whl")):
            name, ver = whl.name.split("-")[:2]
            name = re.sub(r"[_.]+", "-", name).lower()
            lines.append("%s==%s --hash=sha256:%s" % (name, ver, sha256(whl)))
    REQUIREMENTS.write_text("# Generated by `python installer/build.py --lock`; do not edit.\n"
                            + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("locked %d packages into %s" % (len(lines), REQUIREMENTS))


def fetch_python() -> Path:
    CACHE.mkdir(parents=True, exist_ok=True)
    z = CACHE / PYTHON_URL.rsplit("/", 1)[1]
    if not z.exists():
        print("downloading %s" % PYTHON_URL)
        urllib.request.urlretrieve(PYTHON_URL, z)
    got = sha256(z)
    if got != PYTHON_SHA256:
        z.unlink()
        sys.exit("python embeddable checksum mismatch: got %s, expected %s" % (got, PYTHON_SHA256))
    return z


def stage() -> None:
    if not (REPO / "ui" / "build" / "index.html").exists():
        sys.exit("ui/build is missing: npm --prefix ui run build")
    if STAGE.exists():
        shutil.rmtree(STAGE)
    py = STAGE / "python"
    py.mkdir(parents=True)
    with zipfile.ZipFile(fetch_python()) as z:
        z.extractall(py)
    # The embeddable distribution reads sys.path from this file alone. `..` is the install
    # root, so `import app` and `import api` resolve; `import site` turns on site-packages.
    pth = next(py.glob("python3*._pth"))
    pth.write_text("%s\n.\nLib\\site-packages\n..\nimport site\n"
                   % pth.name.replace("._pth", ".zip"), encoding="ascii")
    site = py / "Lib" / "site-packages"
    pip("install", "--only-binary", ":all:", "--require-hashes", "--no-deps", "--no-compile",
        "--target", str(site), "-r", str(REQUIREMENTS))
    sys.path.insert(0, str(REPO))
    from app import provenance
    (STAGE / "BUILD").write_text("%s %s\n" % (version(), provenance.code_revision()),
                                 encoding="ascii")
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc")
    for rel in SHIP:
        src, dst = REPO / rel, STAGE / rel
        if src.is_dir():
            shutil.copytree(src, dst, ignore=ignore)
        else:
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
    print("staged %s" % STAGE)


def find_iscc(given: str | None) -> Path:
    cands = [Path(given)] if given else []
    if on_path := shutil.which("ISCC"):
        cands.append(Path(on_path))
    for cand in cands + ISCC_GUESSES:
        if cand.is_file():
            return cand
    sys.exit("Inno Setup 6 not found; install it or pass --iscc PATH")


def compile_installer(iscc: Path) -> Path:
    DIST.mkdir(exist_ok=True)
    subprocess.run([str(iscc), "/Q", "/DAppVersion=%s" % version(), "/DStaging=%s" % STAGE,
                    "/DOutDir=%s" % DIST, "/DRepo=%s" % REPO, str(HERE / "mockingbird.iss")],
                   check=True)
    out = DIST / ("Mockingbird-Setup-%s.exe" % version())
    print("built %s (%.1f MB)" % (out, out.stat().st_size / 1e6))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--lock", action="store_true")
    ap.add_argument("--iscc")
    a = ap.parse_args()
    if a.lock:
        lock()
        return 0
    stage()
    compile_installer(find_iscc(a.iscc))
    return 0


if __name__ == "__main__":
    sys.exit(main())
